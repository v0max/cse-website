import Link from "next/link";
import type { Person } from "@/lib/content";
import { getSite } from "@/lib/content";

export function SiteHeader({ home = false }: { home?: boolean }) {
  const site = getSite();
  const base = home ? "" : "/";
  return (
    <header className="site-header">
      <div className="wrap site-header__inner">
        <Link href="/" className="brand">
          <span className="brand__mark">{site.shortName}</span>
          <span className="brand__name">{site.name}</span>
        </Link>
        <nav aria-label="Primary" className="site-nav">
          <a href={`${base}#matters`}>Matters</a>
          <a href={`${base}#cases`}>Cases</a>
          <a href={`${base}#experts`}>Experts</a>
          <a href={`${base}#engage`} className="btn btn--accent">
            Contact us
          </a>
        </nav>
      </div>
    </header>
  );
}

export function SiteFooter() {
  const site = getSite();
  const tel = "+1" + site.phone.replace(/\D/g, "");
  return (
    <footer className="site-footer">
      <div className="wrap site-footer__inner">
        <div className="stack-6">
          <span className="site-footer__name">{site.name}</span>
          <span>{site.offices.join(" · ")}</span>
          <span>
            <a href={`tel:${tel}`}>{site.phone}</a> · <a href={`mailto:${site.email}`}>{site.email}</a>
          </span>
        </div>
        <div className="stack-6 site-footer__legal">
          <span>
            © {new Date().getFullYear()} {site.name}. Registered in {site.registeredIn}.
          </span>
          <span>This site sets no cookies and loads no third-party trackers.</span>
          <span>Nothing on this site is legal advice or creates an engagement.</span>
        </div>
      </div>
    </footer>
  );
}

export function SectionHead({ n, title, intro, id }: { n: number; title: string; intro?: string; id?: string }) {
  return (
    <div className="section-head" id={id}>
      <p className="section-head__n">§ {n}</p>
      <div className="section-head__text">
        <h2>{title}</h2>
        {intro ? <p className="section-head__intro">{intro}</p> : null}
      </div>
    </div>
  );
}

export function Portrait({ person, size, className = "" }: { person: Person; size: number; className?: string }) {
  if (!person.portrait) {
    return (
      <div className={`portrait portrait--initials ${className}`} style={{ width: size, height: size }} aria-hidden="true">
        {person.initials}
      </div>
    );
  }
  return (
    // Plain <img>: portraits are small, pre-sized WebP files generated by tools/portraits.
    // eslint-disable-next-line @next/next/no-img-element
    <img
      className={`portrait ${className}`}
      src={person.portrait}
      alt={`Portrait of ${person.name}`}
      width={size}
      height={size}
      loading="lazy"
    />
  );
}
